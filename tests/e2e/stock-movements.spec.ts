import { test, expect } from "@playwright/test";

test.beforeEach(async ({ context }) => {
    await context.addInitScript(() => sessionStorage.setItem("rotalog:mock-auth-user", JSON.stringify({ id: "test", name: "Teste", email: "teste@rotalog.test", role: "SUPPLIER_OPERATOR" })));
});

test("histórico real acompanha reserva e cadastro em outras abas, filtros, recarga e organização", async ({ page, context }) => {
    await page.goto("/fornecedor/estoque");
    const history = page.getByRole("region", { name: "Histórico de movimentações", exact: true });
    await expect(history).toContainText("Nenhuma movimentação registrada");
    const orders = await context.newPage();
    await orders.goto("/fornecedor/pedidos");
    await orders.getByRole("button", { name: "+ Pedido de teste", exact: true }).click();
    await expect(history).toContainText("Nenhuma movimentação registrada");
    const card = orders.locator("article").filter({ hasText: "Cliente fictício" });
    await card.getByRole("button", { name: /^Aceitar pedido/ }).click();
    await orders.getByRole("button", { name: "Confirmar aceite", exact: true }).click();
    await expect(orders.getByRole("dialog")).toHaveCount(0);
    await expect(history.getByRole("row")).toHaveCount(3);
    await expect(history.getByRole("cell", { name: "TESTE-001", exact: true })).toHaveCount(2);
    const position = page.getByRole("region", { name: "Posição de estoque", exact: true });
    const cells = position.getByRole("row").filter({ has: page.getByRole("cell", { name: "PROD-001", exact: true }) }).getByRole("cell");
    await expect(cells.nth(3)).toHaveText("120");
    await expect(cells.nth(4)).toHaveText("1");
    await expect(cells.nth(5)).toHaveText("119");
    const search = history.getByRole("searchbox");
    await search.fill("TESTE-001");
    await expect(history.getByRole("row")).toHaveCount(3);
    await search.fill("PROD-001");
    await expect(history.getByRole("row")).toHaveCount(2);
    await history.getByRole("combobox", { name: "Tipo de movimentação", exact: true }).selectOption("initial-stock");
    await expect(history).toContainText("Nenhuma movimentação corresponde aos filtros");
    await history.getByRole("button", { name: "Limpar", exact: true }).click();
    const products = await context.newPage();
    await products.goto("/fornecedor/produtos");
    await products.getByRole("button", { name: "Novo produto", exact: true }).click();
    const dialog = products.getByRole("dialog");
    await dialog.getByLabel("Código do produto", { exact: true }).fill("HIST-001");
    await dialog.getByLabel("Nome", { exact: true }).fill("Produto do histórico");
    await dialog.getByLabel("Categoria", { exact: true }).fill("Categoria");
    await dialog.getByLabel("Unidade de medida", { exact: true }).fill("kg");
    await dialog.getByLabel("Preço unitário (R$)", { exact: true }).fill("10");
    await dialog.getByLabel("Quantidade inicial em estoque", { exact: true }).fill("3");
    await dialog.getByRole("button", { name: "Salvar produto", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await expect(history.getByRole("row")).toHaveCount(4);
    await expect(history.getByRole("row").nth(1)).toContainText("HIST-001");
    await history.getByRole("combobox", { name: "Tipo de movimentação", exact: true }).selectOption("initial-stock");
    await search.fill("histórico");
    await expect(history.getByRole("row")).toHaveCount(2);
    await expect(history.getByRole("row").nth(1)).toContainText("3 kg");
    await history.getByRole("button", { name: "Limpar", exact: true }).click();
    await page.reload();
    await expect(history.getByRole("row")).toHaveCount(4);
    const before = await history.getByRole("table").innerText();
    await page.reload();
    await expect.poll(() => history.getByRole("table").innerText()).toBe(before);
    await page.getByText("Controles de desenvolvimento", { exact: true }).click();
    await page.getByLabel("Organização ativa", { exact: true }).selectOption("fornecedor-002");
    await expect(history).toContainText("Nenhuma movimentação registrada");
    await page.getByLabel("Organização ativa", { exact: true }).selectOption("fornecedor-001");
    await expect(history.getByRole("row")).toHaveCount(4);
    await history.scrollIntoViewIfNeeded();
    await page.screenshot({ path: "test-results/stock-history-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    const scroll = history.getByRole("region", { name: "Rolagem do histórico de movimentações", exact: true });
    expect(await scroll.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
    await history.scrollIntoViewIfNeeded();
    await page.screenshot({ path: "test-results/stock-history-mobile.png", fullPage: true });
});
