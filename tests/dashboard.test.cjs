assert.equal(getOrderHistory([order('tz-completed', { completedAt: '2026-10-01T02:00:00Z', status: 'Entregue' })], 'a', aliases, filters)[0].month, '2026-09');
const { getOrderDeadline, formatRemaining } = load('src/features/orders/utils/orderDeadline.ts');
const deadlineNow = Date.parse('2026-10-20T12:00:00Z');
assert.equal(getOrderDeadline(order('no-deadline'), deadlineNow).remaining, null);
assert.match(getOrderDeadline(order('no-deadline'), deadlineNow).message, /não informado/);
const timedOrder = order('timed', { acceptanceDeadline: '2026-10-20T09:00:00-04:00', timeZone: 'America/Manaus' });
assert.equal(getOrderDeadline(timedOrder, deadlineNow).remaining, 3600000);
assert.equal(getOrderDeadline(timedOrder, deadlineNow + 1000).remaining, 3599000);
assert.equal(getOrderDeadline(timedOrder, deadlineNow + 3600000).remaining, 0);
assert.equal(formatRemaining(0), 'Prazo encerrado');
assert.equal(formatRemaining(3600000), '1h 0min 0s restantes');
assert.equal(getOrderDeadline({ ...timedOrder, commercialStatus: 'Aceito' }, deadlineNow).remaining, null);
assert.equal(getOrderDeadline({ ...timedOrder, acceptanceDeadline: '2026-10-20T09:00:00' }, deadlineNow).remaining, null);
assert.equal(getOrderDeadline({ ...timedOrder, acceptanceDeadline: 'invalid' }, deadlineNow).remaining, null);
assert.match(getOrderDeadline({ ...timedOrder, timeZone: 'invalid-zone' }, deadlineNow).zoneMessage, /inválido/);
console.log('Annual filter, bounded periods, monthly history, search, filters, scope and immutability passed.');
