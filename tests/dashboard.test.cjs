assert.equal(getDashboardOrders([order('timezone-year', { date: '2026-01-01T02:00:00Z' })], 'a', 2025).metrics[0].value, 1);
const { getOrderHistory } = load('src/features/orders/utils/orderHistory.ts', { './orderStage': stage });
const historyOrders = [order('active'), order('delivered', { date: '2026-01-01', completedAt: '2026-10-01T12:00:00Z', status: 'Entregue' }), order('refused', { date: '2026-01-01', commercialStatus: 'Recusado', rejection: { rejectedAt: '2026-09-15T12:00:00Z' } }), order('older', { date: '2025-01-01', completedAt: '2025-12-31T12:00:00Z', custodyStatus: 'Entregue' }), order('foreign-history', { organizationId: 'b', status: 'Entregue' })];
const snapshot = JSON.stringify(historyOrders);
const filters = { search: '', status: '', from: '', to: '' };
const aliases = new Map([['refused', 'TESTE-001']]);
const groups = getOrderHistory(historyOrders, 'a', aliases, filters);
assert.deepEqual(Array.from(groups, group => group.month), ['2026-10', '2026-09', '2025-12']);
assert.equal(groups.reduce((sum, group) => sum + group.records.length, 0), 3);
assert.equal(getOrderHistory(historyOrders, 'a', aliases, { ...filters, search: 'teste-001' })[0].records[0].id, 'refused');
assert.equal(getOrderHistory(historyOrders, 'a', aliases, { ...filters, status: 'refused' }).length, 1);
assert.equal(getOrderHistory(historyOrders, 'a', aliases, { ...filters, from: '2026-09-01', to: '2026-09-30' }).length, 1);
assert.equal(getOrderHistory(historyOrders, 'a', aliases, { ...filters, from: '2026-10-02' }).length, 0);
assert.equal(getOrderHistory(historyOrders, 'b', aliases, filters)[0].records[0].id, 'foreign-history');
assert.equal(getOrderHistory([], 'a', aliases, filters).length, 0);
assert.equal(JSON.stringify(historyOrders), snapshot);
assert.equal(getOrderHistory([order('no-date', { date: undefined, status: 'Entregue' }), order('bad-date', { date: '2026-99-99', status: 'Entregue' })], 'a', aliases, filters)[0].month, 'unknown');
const legacyHistory = [order('legacy-done', { date: '2026-09-01', status: 'Entregue' }), order('legacy-refused', { date: '2026-09-01', commercialStatus: 'Recusado' })];
assert.equal(getOrderHistory(legacyHistory, 'a', aliases, filters)[0].month, 'unknown');
